#!/usr/bin/env node
/**
 * Generates src/app/flare/flare-config.ts (gitignored) from process.env at
 * Netlify build time.
 *
 * Angular compiles environment files straight into the bundle, and this
 * repo's only existing mechanism for that — src/environments/environment.ts /
 * environment.prod.ts, swapped by angular.json's `fileReplacements` — is
 * tracked in git. There is no Next-style NEXT_PUBLIC_ or Vite-style
 * import.meta.env build-time env-var injection here, so the flare ingest key
 * cannot go through that pair without landing in a commit. This script is the
 * one place FLARE_KEY ever touches disk in this repo; its output is
 * gitignored (see .gitignore) so it can never be committed by accident.
 *
 * Netlify's own release identifier is COMMIT_REF, not Vercel's
 * VERCEL_GIT_COMMIT_SHA (see Netlify's build environment docs) — the fleet's
 * other apps use the Vercel name because they all deploy on Vercel; marian
 * does not.
 *
 * Always succeeds, even with no env vars set (a plain local `ng build`): it
 * writes the same empty-string shape as flare-config.example.ts, which makes
 * flareEnabled() in flare.ts permanently false rather than failing the
 * build. Run directly for local development:
 *   node scripts/gen-flare-env.mjs
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "../src/app/flare/flare-config.ts");

const url = process.env.FLARE_URL ?? "";
const key = process.env.FLARE_KEY ?? "";
const release = process.env.COMMIT_REF ?? null;

const body = `// GENERATED by scripts/gen-flare-env.mjs at build time — do not edit or
// commit (see .gitignore). Regenerate locally with:
//   node scripts/gen-flare-env.mjs
// See flare-config.example.ts for the tracked template this shape follows.

export const FLARE_URL: string = ${JSON.stringify(url)};
export const FLARE_KEY: string = ${JSON.stringify(key)};
export const FLARE_RELEASE: string | null = ${release === null ? "null" : JSON.stringify(release)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);

// Never print the key value itself — name, presence, and length only.
console.log(
  `gen-flare-env: wrote ${OUT} ` +
    `(FLARE_URL ${url ? "set" : "empty"}, ` +
    `FLARE_KEY ${key ? `set, len ${key.length}` : "empty"}, ` +
    `COMMIT_REF ${release ?? "unset"})`,
);
